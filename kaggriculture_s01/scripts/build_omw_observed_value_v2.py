#!/usr/bin/env python3
"""Build the local OMW observed-value experiment as one Kaggle main.py."""

from __future__ import annotations

import base64
import hashlib
import json
import tarfile
import zlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / "references/kaggle-scan-2026-09-21/extracted/one-more-wheat/main.py"
V1 = ROOT / "experiments/omw-observed-front-run-v1/main.py"
V2 = ROOT / "experiments/omw-observed-value-front-run-v2/main.py"
OUT_DIR = ROOT / "submissions/omw-observed-value-front-run-v2"
OUT_MAIN = OUT_DIR / "main.py"
OUT_TAR = ROOT / "submissions/omw-observed-value-front-run-v2.tar.gz"
OUT_MANIFEST = ROOT / "submissions/omw-observed-value-front-run-v2.manifest.json"

V1_MARKER = 'PRODUCTS = ("MILK", "WOOL", "STRAWBERRY", "MELON", "EGG")'
V2_MARKER = "# Exact defaults from kaggle-environments 1.32.7, Apache-2.0."


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def tail(path: Path, marker: str) -> str:
    source = path.read_text()
    offset = source.index(marker)
    return source[offset:]


def blob(source: str) -> str:
    return base64.b85encode(zlib.compress(source.encode(), 9)).decode()


def build_loader(v1_source: str, v2_source: str) -> str:
    return f'''

# ---------------------------------------------------------------------------
# Local OMW observed-value front-run v2 overlay.
# Generated by scripts/build_omw_observed_value_v2.py.  The compressed modules
# contain only the local overlay tails; the frozen One More Wheat parent above
# remains byte-for-byte unchanged.
# ---------------------------------------------------------------------------
import types as _ov2_types
import statistics as _ov2_statistics
import math as _ov2_math
import base64 as _ov2_base64
import zlib as _ov2_zlib

_OV2_BASE_AGENT = agent
_ov2_parent = _ov2_types.SimpleNamespace(
    agent=_OV2_BASE_AGENT,
    _IMPL=_IMPL,
    FarmView=FarmView,
    projected_shed=projected_shed,
)
_ov2_v1_source = _ov2_zlib.decompress(
    _ov2_base64.b85decode({blob(v1_source)!r})
).decode()
_ov2_v1_ns = {{
    "__builtins__": __builtins__,
    "__name__": "_embedded_omw_observed_front_run_v1",
    "statistics": _ov2_statistics,
    "_PARENT": _ov2_parent,
}}
exec(compile(_ov2_v1_source, "<embedded-omw-observed-front-run-v1>", "exec"), _ov2_v1_ns)
_ov2_v1 = _ov2_types.SimpleNamespace(**_ov2_v1_ns)

_ov2_v2_source = _ov2_zlib.decompress(
    _ov2_base64.b85decode({blob(v2_source)!r})
).decode()
_ov2_v2_ns = {{
    "__builtins__": __builtins__,
    "__name__": "_embedded_omw_observed_value_front_run_v2",
    "math": _ov2_math,
    "_V1": _ov2_v1,
}}
exec(compile(_ov2_v2_source, "<embedded-omw-observed-value-front-run-v2>", "exec"), _ov2_v2_ns)
agent = _ov2_v2_ns["agent"]
'''


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    base_source = BASE.read_text()
    v1_source = tail(V1, V1_MARKER)
    v2_source = tail(V2, V2_MARKER)
    OUT_MAIN.write_text(base_source.rstrip() + "\n" + build_loader(v1_source, v2_source))
    compile(OUT_MAIN.read_text(), str(OUT_MAIN), "exec")
    with tarfile.open(OUT_TAR, "w:gz") as archive:
        archive.add(OUT_MAIN, arcname="main.py")
    manifest = {
        "competition": "kaggriculture",
        "policy": "omw_observed_value_front_run_v2",
        "parent": "one_more_wheat_public_exact",
        "parent_main_sha256": sha256(BASE),
        "main_sha256": sha256(OUT_MAIN),
        "archive_sha256": sha256(OUT_TAR),
        "archive_members": ["main.py"],
        "local_source": str(V2.relative_to(ROOT)),
        "status": "built_not_submitted",
    }
    OUT_MANIFEST.write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()

